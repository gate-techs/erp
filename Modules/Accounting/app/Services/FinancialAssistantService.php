            $data = $catalog[$routeName];
            $data['route'] = $routeName;
            return $data;
        }

        // Try fuzzy route name matching (e.g. accounting.reports.*)
        if ($routeName) {
            foreach ($catalog as $key => $info) {
                if (str_starts_with($routeName, str_replace('.index', '', $key))) {
                    $info['route'] = $key;
                    return $info;
                }
            }
        }

        // Default generic accounting context
        return [
