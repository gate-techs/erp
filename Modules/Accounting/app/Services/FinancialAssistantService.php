    /**
     * Get real-time financial facts from the accounting database.
     */
    public function getRealtimeFinancialFacts(?int $entityId = null): array
    {
        try {
            $dashboardData = $this->dashboardService->getDashboardData($entityId);

            $cashAccounts = collect($dashboardData['cashAccounts'] ?? [])->map(function ($item) {
                return [
                    'name'    => $item['name'] ?? '',
                    'type'    => $item['type'] ?? '',
                    'balance' => $item['balance'] ?? 0,
                ];
            })->toArray();

            $pending = $dashboardData['pending'] ?? [];
            $kpis = $dashboardData['kpis'] ?? [];
            $currencySymbol = $dashboardData['currencySymbol'] ?? 'د.ك';

            return [
                'currency'        => $currencySymbol,
                'total_liquidity' => collect($cashAccounts)->sum('balance'),
                'cash_accounts'   => $cashAccounts,
                'pending_actions' => [
                    'draft_entries' => $pending['draft_entries'] ?? 0,
                    'draft_recs'    => $pending['draft_recs'] ?? 0,
                ],
                'kpis'            => [
                    'revenue'     => $kpis['revenue'] ?? 0,
                    'expenses'    => $kpis['expenses'] ?? 0,
                    'net_profit'  => $kpis['net_profit'] ?? 0,
                ],
            ];
        } catch (Exception $e) {
            return [
                'error' => 'تعذر جلب البيانات اللحظية: ' . $e->getMessage(),
            ];
        }
    }

    /**
     * Ask the Financial Assistant a question.
     * Automatically routes to whichever provider is assigned to `financial_assistant` in `/settings/ai`.
     */
    public function ask(
        string $question,
        ?string $currentRoute = null,
        ?string $currentUrl = null,
        ?int $entityId = null,
        array $history = []
    ): array {
        $screenContext = $this->resolveScreenContext($currentRoute, $currentUrl);
        $facts = $this->getRealtimeFinancialFacts($entityId);

        $prompt = $this->buildSystemPrompt($screenContext, $facts, $question, $history);

        try {
            // Task 'financial_assistant' resolves provider dynamically from /settings/ai
            $answer = $this->aiService->generate($prompt, [
                'temperature' => 0.2,
                'max_tokens'  => 1200,
            ], null, 'financial_assistant');

            return [
                'success'        => true,
                'answer'         => $answer,
                'screen_context' => $screenContext,
                'suggestions'    => $screenContext['suggestions'] ?? [],
            ];
        } catch (Exception $e) {
            // Provide a graceful explanation with instruction to configure AI provider in /settings/ai
            $fallbackMessage = "⚠️ **تنبيه مزود الذكاء الاصطناعي:**\n\n"
                . "لم يتم إكمال الرد عبر نموذج الذكاء الاصطناعي. السبب: " . $e->getMessage() . "\n\n"
                . "💡 **لحل المشكلة وتفعيل النموذج:**\n"
                . "يرجى التوجه إلى شاشة **[إعدادات الذكاء الاصطناعي](/settings/ai)**، ثم الذهاب لتبويب **توجيه مهام الذكاء الاصطناعي (AI Task Routing)** والتأكد من تعيين مزود فعال (مثل Google Gemini أو OpenAI) لمهمة **«المساعد المالي والمرشد الذكي»**.";

            return [
                'success'        => false,
                'answer'         => $fallbackMessage,
                'screen_context' => $screenContext,
                'suggestions'    => $screenContext['suggestions'] ?? [],
            ];
        }
    }

    /**
     * Build strict, zero-hallucination system prompt.
     */
    protected function buildSystemPrompt(
        array $screenContext,
        array $facts,
        string $question,
        array $history = []
    ): string {
        $factsJson = json_encode($facts, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT);
        $screenJson = json_encode($screenContext, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT);

        $conversationText = '';
        if (!empty($history)) {
            $conversationText = "سياق المحادثة السابقة:\n";
            foreach (array_slice($history, -4) as $msg) {
                $role = ($msg['role'] ?? 'user') === 'user' ? 'المستخدم' : 'المساعد';
                $content = $msg['content'] ?? '';
                $conversationText .= "{$role}: {$content}\n";
            }
            $conversationText .= "\n";
        }

        return <<<PROMPT
أنت «المساعد المالي والمرشد الذكي» لنظام GateTech ERP - موديول المحاسبة المالية.
دورك محدد وصارم في مهمتين رئيسيتين فقط:
1. **الرد المالي الذكي:** الإجابة عن الأرقام والمؤشرات والبيانات المالية من واقع السجلات المحاسبية والبيانات اللحظية المرفقة لك أدناه فقط. يمنع منعاً باتاً اختراع أو افتراض أي أرقام خارج هذا النطاق (Zero-Hallucination).
2. **مرشد الشاشات وتوجيه العمليات:** مساعدة المستخدم في فهم الشاشة الحالية التي يقف عليها، وإرشاده خطوة بخطوة بالترتيب لتنفيذ أي عملية محاسبية بدقة، وتوضيح الشروط المحاسبية (مثل توازن القيد، تواريخ الإقفال، وخطوات التسوية البنكية).

### معلومات الشاشة الحالية التي يقف عليها المستخدم:
{$screenJson}

### البيانات المحاسبية اللحظية المأخوذة من قاعدة بيانات النظام:
{$factsJson}

{$conversationText}
### قواعد الإجابة:
1. أجب باللغة العربية الفصحى الواضحة والمهنية المناسبة للمديرين والمحاسبين.
2. إذا كان السؤال عن "هذه الشاشة" أو "كيف أستخدمها" أو "ما وظيفتها": اشرح بناءً على معلومات الشاشة الحالية المرفقة، مع تقديم خطوات تنفيذية مرقمة.
3. إذا كان السؤال عن السيولة أو الأرباح أو القيود المعلقة: استخدم الأرقام الحقيقية المذكورة في البيانات اللحظية فقط.
4. إذا سأل المستخدم عن معلومة غير متوفرة في النظام أو خارج نطاق المحاسبة: وضح بلباقة أن هذه المعلومة غير مسجلة في السجلات المحاسبية الحالية للنظام.
5. نسق إجابتك باستخدام Markdown (نقاط مرقمة، خط عريض، جداول خفيفة إن لزم).

سؤال المستخدم:
{$question}
PROMPT;
    }
